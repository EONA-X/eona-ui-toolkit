    writeln!(s)?;
    writeln!(s, "```js")?;
    writeln!(s, "import '{PACKAGE_NAME}'; // tokens + components + ontology")?;
    writeln!(s, "```")?;
    writeln!(s)?;
    writeln!(s, "```html")?;
    writeln!(s, "<div class=\"eona-ui\"> <!-- every component goes inside one of these --> </div>")?;
    writeln!(s, "```")?;
    writeln!(s)?;
    writeln!(s, "**Every rule is scoped under `{SCOPE}`.** Put that class on an ancestor of the components — the")?;
