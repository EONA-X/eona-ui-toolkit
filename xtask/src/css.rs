    writeln!(s, "| `{PACKAGE_NAME}` | `index.css`: tokens, components and ontology, in that order |")?;
    writeln!(s, "| `{PACKAGE_NAME}/tokens.css` | the charter palette and the semantic layer (`--eona-surface-page`, …), as `:root` custom properties; dark mode via `<html data-theme=\"dark\">` |")?;
