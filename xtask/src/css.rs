//! Stage: `css`. Writes `@eona-x/ui-toolkit-css`, the stylesheet both generated
//! packages' markup is meaningless without.
//!
//! A pure function of `assets/`, the stylesheets the crate exposes as
//! `TOKENS_CSS`, `COMPONENTS_CSS` and `ONTOLOGY_CSS` (`src/lib.rs`) — but not a
//! copy of them. `components.css` was written for whole EONA-X pages: it opens
//! with a reset on `*`, `html`, `body`, `img`, `a`, `h1`-`h4`, `p` and `code` and
//! pushes `html > body` down 156px for the fixed header. Imported into somebody
//! else's app that restyles and displaces the whole host page, and its class
//! names (`.btn`, `.wrap`) are the ones every other CSS framework uses too. So
//! (eona-x/backlog#808, Layer 3):
//!
//! - `tokens.css` is copied as is — it declares `:root` custom properties only;
//! - every component rule is scoped under `.eona-ui`, which the consumer puts
//!   on an ancestor of the components;
//! - the page shell moves to an opt-in `page.css`, verbatim, for apps that *are*
//!   EONA-X pages; inside `.eona-ui` the element resets still apply, and
//!   `body`'s typography is carried by `.eona-ui` itself, so a component renders
//!   the same in a host page as on an EONA-X one.
//!
//! The transform understands exactly what these sheets contain — style rules
//! and `@media` — and refuses anything else rather than guessing at it.
//!
//! Nothing here needs a render, so the drift gate recomputes
//! the package on every run — replay path included — and diffs it, rather than
//! trusting a manifest: an edit to `assets/` moves neither `srcHash` nor
//! `generatorHash`, and a hash-only gate would not see it.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{bail, Context, Result};

use crate::emit::{GENERATOR, PACKAGE_VERSION};

pub const PACKAGE_DIR: &str = "packages/css";
pub const PACKAGE_NAME: &str = "@eona-x/ui-toolkit-css";

/// The class an ancestor of the components must carry.
pub const SCOPE: &str = ".eona-ui";

/// The sheets `index.css` imports, in cascade order: tokens first, because both
/// others read its custom properties. `page.css` is deliberately not one.
const SHEETS: &[&str] = &["tokens.css", "components.css", "ontology.css"];
const ASSETS: &[&str] = &["logo/logo-transparent.svg"];

/// `body` declarations that are typography, and so belong to the scope root.
/// Its `margin` and `background` are the page's business, not the components'.
const INHERITED: &[&str] =
    &["font-family", "color", "font-size", "line-height", "-webkit-font-smoothing"];

/// The whole package as relative path -> contents.
pub fn render_package(root: &Path) -> Result<BTreeMap<String, String>> {
    let read = |name: &str| {
        let path = root.join("assets").join(name);
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))
    };
    let mut files = BTreeMap::new();
    files.insert("tokens.css".into(), read("tokens.css")?);
    let components = split(&read("components.css")?).context("scoping assets/components.css")?;
    files.insert("components.css".into(), banner("components.css", true) + &components.scoped);
    files.insert("page.css".into(), banner("components.css", false) + &components.page);
    let ontology = split(&read("ontology.css")?).context("scoping assets/ontology.css")?;
    if !ontology.page.is_empty() {
        anyhow::bail!("assets/ontology.css styles the page itself; only components.css may");
    }
    files.insert("ontology.css".into(), banner("ontology.css", true) + &ontology.scoped);
    for name in ASSETS {
        files.insert((*name).to_string(), read(name)?);
    }
    files.insert("index.css".into(), index_css()?);
    files.insert("package.json".into(), package_json()?);
    files.insert("README.md".into(), readme_md()?);
    Ok(files)
}

fn index_css() -> Result<String> {
    let mut s = String::new();
    writeln!(s, "/* Generated by `{GENERATOR}` from the eona-ui-toolkit Yew crate. Do not edit. */")?;
    writeln!(s, "/* Everything the generated components need, in cascade order. */")?;
    for sheet in SHEETS {
        writeln!(s, "@import \"./{sheet}\";")?;
    }
    Ok(s)
}

fn banner(source: &str, scoped: bool) -> String {
    let what = if scoped {
        format!("every rule scoped under `{SCOPE}`; put that class on an ancestor of the components")
    } else {
        "the page shell only — opt in when the whole page is an EONA-X page".to_string()
    };
    format!(
        "/* Generated by `{GENERATOR}` from assets/{source} in the eona-ui-toolkit Yew crate. \
         Do not edit. */\n/* {what}. */\n\n"
    )
}

// ------------------------------------------------------------------ transform

/// One sheet, split.
#[derive(Debug, Default, PartialEq)]
struct Split {
    /// Component rules under [`SCOPE`], plus the element resets re-applied
    /// inside it and `body`'s typography on the scope root.
    scoped: String,
    /// The page shell, verbatim: every rule whose selector names no class, id
    /// or attribute.
    page: String,
}

/// A style rule: its selectors, split at top-level commas, and its body.
#[derive(Debug)]
struct Rule {
    selectors: Vec<String>,
    body: String,
}

#[derive(Debug)]
enum Item {
    Rule(Rule),
    Media { prelude: String, rules: Vec<Rule> },
}

fn split(css: &str) -> Result<Split> {
    let items = parse(&strip_comments(css)?)?;
    let mut out = Split::default();
    for item in &items {
        match item {
            Item::Rule(r) => {
                let (scoped, page) = split_rule(r);
                out.scoped.push_str(&scoped);
                out.page.push_str(&page);
            }
            Item::Media { prelude, rules } => {
                let (mut scoped, mut page) = (String::new(), String::new());
                for r in rules {
                    let (s, p) = split_rule(r);
                    scoped.push_str(&s);
                    page.push_str(&p);
                }
                for (text, sink) in [(scoped, &mut out.scoped), (page, &mut out.page)] {
                    if !text.is_empty() {
                        sink.push_str(&format!("{prelude} {{\n{}}}\n", indent(&text)));
                    }
                }
            }
        }
    }
    Ok(out)
}

/// One rule -> (its scoped form, its page-shell form). Either may be empty.
fn split_rule(r: &Rule) -> (String, String) {
    let mut scoped: Vec<String> = Vec::new();
    let mut page: Vec<&str> = Vec::new();
    let mut root_decls = String::new();
    for sel in &r.selectors {
        if !is_page(sel) {
            scoped.push(format!("{SCOPE} {sel}"));
            continue;
        }
        page.push(sel);
        match head(sel) {
            // The document itself: nothing to re-apply inside a host's page.
            "html" => {}
            "body" if sel.trim() == "body" => root_decls = typography(&r.body),
            "body" => {}
            // The universal reset covers the scope root too.
            "*" => {
                scoped.push(SCOPE.to_string());
                scoped.push(format!("{SCOPE} {sel}"));
            }
            _ => scoped.push(format!("{SCOPE} {sel}")),
        }
    }
    let mut s = String::new();
    if !scoped.is_empty() {
        s.push_str(&format!("{} {{{}}}\n", scoped.join(",\n"), r.body));
    }
    if !root_decls.is_empty() {
        s.push_str(&format!("{SCOPE} {{{root_decls}}}\n"));
    }
    let p = if page.is_empty() {
        String::new()
    } else {
        format!("{} {{{}}}\n", page.join(",\n"), r.body)
    };
    (s, p)
}

/// A selector that names no class, id or attribute styles the page, not a
/// component: `*`, `html > body`, `a:hover`, `h1`.
fn is_page(sel: &str) -> bool {
    !sel.contains(['.', '#', '['])
}

/// The first compound's element name (`html` of `html > body`, `a` of `a:hover`).
fn head(sel: &str) -> &str {
    let first = sel.trim().split(|c: char| c.is_whitespace() || c == '>' || c == '+' || c == '~').next().unwrap_or("");
    first.split(':').next().unwrap_or("")
}

fn typography(body: &str) -> String {
    let kept: Vec<String> = body
        .split(';')
        .map(str::trim)
        .filter(|d| d.split(':').next().is_some_and(|p| INHERITED.contains(&p.trim())))
        .map(|d| format!("\n  {d};"))
        .collect();
    if kept.is_empty() {
        String::new()
    } else {
        format!("{}\n", kept.concat())
    }
}

fn indent(block: &str) -> String {
    block.lines().map(|l| if l.is_empty() { "\n".to_string() } else { format!("  {l}\n") }).collect()
}

fn strip_comments(css: &str) -> Result<String> {
    let mut out = String::with_capacity(css.len());
    let mut rest = css;
    while let Some(i) = rest.find("/*") {
        out.push_str(&rest[..i]);
        let Some(end) = rest[i + 2..].find("*/") else { bail!("unterminated comment") };
        rest = &rest[i + 2 + end + 2..];
    }
    out.push_str(rest);
    if out.contains(['"', '\'']) && out.contains(['{', '}']) {
        // Quoted strings are fine as long as none holds a brace, comma or
        // semicolon the scanner below would misread.
        for q in ['"', '\''] {
            for (n, part) in out.split(q).enumerate() {
                if n % 2 == 1 && part.contains(['{', '}', ',', ';']) {
                    bail!("a quoted string holds {{, }}, , or ; — {q}{part}{q}");
                }
            }
        }
    }
    Ok(out)
}

fn parse(css: &str) -> Result<Vec<Item>> {
    let mut items = Vec::new();
    let mut rest = css.trim_start();
    while !rest.is_empty() {
        let open = rest.find('{').with_context(|| format!("trailing text: {}", snippet(rest)))?;
        let prelude = rest[..open].trim();
        if prelude.contains('}') || prelude.contains(';') {
            bail!("stray text before a rule: {}", snippet(prelude));
        }
        if let Some(at) = prelude.strip_prefix('@') {
            if !at.starts_with("media") {
                bail!("@{} is not something this transform understands", at.split_whitespace().next().unwrap_or(""));
            }
            let (inner, after) = block(&rest[open..])?;
            items.push(Item::Media { prelude: prelude.to_string(), rules: parse_rules(inner)? });
            rest = after.trim_start();
        } else {
            let close = rest[open..].find('}').context("unclosed rule")? + open;
            let body = &rest[open + 1..close];
            if body.contains('{') {
                bail!("nested rule under {}: CSS nesting is not supported", snippet(prelude));
            }
            items.push(Item::Rule(Rule { selectors: selectors(prelude)?, body: body.to_string() }));
            rest = rest[close + 1..].trim_start();
        }
    }
    Ok(items)
}

fn parse_rules(css: &str) -> Result<Vec<Rule>> {
    parse(css)?
        .into_iter()
        .map(|i| match i {
            Item::Rule(r) => Ok(r),
            Item::Media { prelude, .. } => bail!("{prelude} nested in @media is not supported"),
        })
        .collect()
}

/// `{ ... }` with nested braces, starting at the `{`: (inside, after).
fn block(s: &str) -> Result<(&str, &str)> {
    let mut depth = 0usize;
    for (i, c) in s.char_indices() {
        match c {
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if depth == 0 {
                    return Ok((&s[1..i], &s[i + 1..]));
                }
            }
            _ => {}
        }
    }
    bail!("unbalanced braces in {}", snippet(s))
}

/// Split a selector list at commas outside `()` and `[]` — `:has(a, b)` is one.
fn selectors(list: &str) -> Result<Vec<String>> {
    let mut out = Vec::new();
    let (mut depth, mut start) = (0i32, 0);
    for (i, c) in list.char_indices() {
        match c {
            '(' | '[' => depth += 1,
            ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                out.push(list[start..i].split_whitespace().collect::<Vec<_>>().join(" "));
                start = i + 1;
            }
            _ => {}
        }
    }
    out.push(list[start..].split_whitespace().collect::<Vec<_>>().join(" "));
    if out.iter().any(String::is_empty) || depth != 0 {
        bail!("malformed selector list: {}", snippet(list));
    }
    if out.iter().any(|s| s.contains('&')) {
        bail!("nesting selector `&` in {}", snippet(list));
    }
    Ok(out)
}

fn snippet(s: &str) -> String {
    let one: String = s.split_whitespace().collect::<Vec<_>>().join(" ");
    one.chars().take(60).collect()
}

fn package_json() -> Result<String> {
    let mut exports = serde_json::Map::new();
    exports.insert(".".into(), "./index.css".into());
    for sheet in SHEETS.iter().chain(&["page.css"]) {
        exports.insert(format!("./{sheet}"), format!("./{sheet}").into());
    }
    exports.insert("./logo/*".into(), "./logo/*".into());
    exports.insert("./package.json".into(), "./package.json".into());
    let v = serde_json::json!({
        "//": format!(
            "Generated by `{GENERATOR}` from the eona-ui-toolkit Yew crate. Do not edit — the \
             next bridgegen overwrites this file."
        ),
        "name": PACKAGE_NAME,
        "version": PACKAGE_VERSION,
        "description": "The EONA-X design system's stylesheets: charter tokens, component styles and ontology badges, as shipped by the eona-ui-toolkit Yew crate.",
        "license": "Apache-2.0",
        "repository": {
            "type": "git",
            "url": "git+https://github.com/EONA-X/eona-ui-toolkit.git",
            "directory": PACKAGE_DIR,
        },
        "style": "./index.css",
        "main": "./index.css",
        "exports": exports,
        // CSS is a side effect by definition: a bundler must never drop an
        // `import '@eona-x/ui-toolkit-css'` for having no bindings.
        "sideEffects": ["*.css"],
        "files": ["*.css", "logo", "README.md"],
        "publishConfig": { "access": "public", "provenance": true },
    });
    Ok(format!("{}\n", serde_json::to_string_pretty(&v)?))
}

